const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium',args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8000/'+(process.env.STANDALONE?'Synthia-Dual-Swarm.html':''));
 await page.waitForFunction(()=>window.synthia?.getStatus().fieldReady,{timeout:30000});
 await page.click('#field-run');
 assert.equal(await page.locator('.journey').isVisible(),false);assert.equal(await page.locator('.inspector').isVisible(),false);
 assert.equal(await page.evaluate(()=>window.synthia.getStatus().fieldObjects),64);
 const bounds=await page.locator('#field-canvas').boundingBox();assert.ok(bounds.width>1400&&bounds.height>600);
 const ids=await page.evaluate(()=>window.synthia.getState().entities.map(e=>e.id));
 await page.getByRole('button',{name:'Movement',exact:true}).first().click();
 assert.deepEqual(await page.evaluate(()=>window.synthia.getState().entities.map(e=>e.id)),ids);
 await page.getByRole('button',{name:'Space',exact:true}).first().click();
 await page.click('#field-signal');await page.click('#field-step');
 await page.waitForFunction(()=>window.synthia.getState().entities.find(e=>e.id==='primitive.swarm').state.inputs.length===1);
 assert.equal(await page.evaluate(()=>window.synthia.getState().entities.find(e=>e.id==='field').state.tick),0);
 await page.screenshot({path:path.join(__dirname,'../docs/relational-world-desktop.png')});
 await page.click('#inspector-toggle');await page.selectOption('#entity-select','field.gate.11');
 await page.click('#field-analyze');await page.waitForFunction(()=>!window.synthia.getStatus().busy);
 assert.ok(await page.locator('#field-analysis').textContent());
 await page.click('#field-enter');await page.waitForFunction(()=>window.synthia.getStatus().fieldObjects===6);
 await page.selectOption('#entity-select','field.gate.11.line.1');await page.click('#field-enter');
 await page.waitForFunction(()=>window.synthia.getState().entities.some(e=>e.id==='field.gate.11.line.1.contents'));
 assert.equal(await page.evaluate(()=>window.synthia.getStatus().fieldObjects),6);
 await page.screenshot({path:path.join(__dirname,'../docs/relational-world-constituents.png')});
 assert.equal(await page.evaluate(()=>window.synthia.verifyReplay()),true);
 await page.click('#field-up');await page.click('#field-up');
 await page.click('#inspector-toggle');await page.click('#embodied-tab');
 await page.waitForFunction(()=>window.synthia.getStatus().humanReady&&window.synthia.getStatus().wolfReady,null,{timeout:60000});
 await page.screenshot({path:path.join(__dirname,'../docs/relational-world-bodies.png')});
 await page.click('#world-tab');await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(500);assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 const mobile=await page.locator('#field-canvas').boundingBox();assert.ok(mobile.height>350);
 await page.screenshot({path:path.join(__dirname,'../docs/relational-world-mobile.png')});
 assert.deepEqual(errors,[]);console.log(JSON.stringify({standalone:!!process.env.STANDALONE,world:true,perspectives:true,recursive:true,factory:true,replay:true,mobile:true,errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
