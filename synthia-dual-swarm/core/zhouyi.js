// Zhouyi: the Movement dimension's I Ching (owner's assignment, 2026-11-13).
// Everything is computed by rule and checked against Richard Rutt, "The Book of Changes
// (Zhouyi)": Contents ch. pp.83-144, Divination ch. pp.162-201.
// Bit convention: bit 0 = line 1 (bottom); 1 = whole/yang, 0 = broken/yin.
import {KING_WEN_BY_TRIGRAMS} from './semantic-address.js';

const GATE_BY_FIGURE=KING_WEN_BY_TRIGRAMS;
const FIGURE_BY_GATE=new Map([...KING_WEN_BY_TRIGRAMS].map(([f,g])=>[g,f]));
const check=(ok,msg)=>{if(!ok)throw new RangeError(msg);};
export const figureOf=gate=>{const f=FIGURE_BY_GATE.get(gate);check(f!==undefined,'gate must be 1-64');return f;};
export const gateOf=figure=>{const g=GATE_BY_FIGURE.get(figure);check(g!==undefined,'figure must be 0-63');return g;};
export const linesOf=figure=>Array.from({length:6},(_,i)=>(figure>>i)&1);
export const figureFromLines=lines=>lines.reduce((f,b,i)=>f|((b&1)<<i),0);

// ---- The two pair operations of the received order (Rutt p.102) ----
// Inversion turns the figure upside down; counterchange swaps whole and broken.
export const invert=figure=>figureFromLines(linesOf(figure).reverse());
export const counterchange=figure=>figure^63;
// Partner in the received order: the inverted figure, or for the eight figures that
// read the same inverted, the counterchanged one.
export function partner(gate){const f=figureOf(gate),i=invert(f);return gateOf(i===f?counterchange(f):i);}

// ---- Trigrams and the family (Rutt p.163, Table 15; 8th Wing) ----
// A trigram's family comes from its lines: all yang = father, all yin = mother;
// one yang line = a son, one yin line = a daughter, rank by where that odd line sits
// (bottom = 1st, middle = 2nd, top = 3rd).
export function family(trigram){
 check(Number.isInteger(trigram)&&trigram>=0&&trigram<8,'trigram must be 0-7');
 const ones=[0,1,2].filter(i=>(trigram>>i)&1);
 if(ones.length===3)return {role:'father',rank:0};
 if(ones.length===0)return {role:'mother',rank:0};
 if(ones.length===1)return {role:'son',rank:ones[0]+1};
 const zero=[0,1,2].find(i=>!((trigram>>i)&1));return {role:'daughter',rank:zero+1};
}
export const lower=f=>f&7, upper=f=>f>>3;
// Nuclear (interlocking) trigrams: lines 2-4 and 3-5 (Rutt p.97).
export const nuclear=f=>({lower:(f>>1)&7,upper:(f>>2)&7});
const trigramFor=(role,rank)=>[...Array(8).keys()].find(t=>{const x=family(t);return x.role===role&&x.rank===rank;});

// ---- The Mawangdui order, generated by its family rule (Rutt pp.114-116) ----
// Upper trigrams: father, 3rd son, 2nd son, 1st son; mother, 3rd, 2nd, 1st daughter.
// Lower trigrams: father, mother; 3rd son, 3rd daughter; 2nd son, 2nd daughter; 1st son,
// 1st daughter; except that each octet opens with its upper trigram doubled.
export function mawangduiOrder(){
 const UP=[['father',0],['son',3],['son',2],['son',1],['mother',0],['daughter',3],['daughter',2],['daughter',1]].map(r=>trigramFor(...r));
 const LO=[['father',0],['mother',0],['son',3],['daughter',3],['son',2],['daughter',2],['son',1],['daughter',1]].map(r=>trigramFor(...r));
 const out=[];
 for(const u of UP){out.push(gateOf((u<<3)|u));for(const l of LO)if(l!==u)out.push(gateOf((u<<3)|l));}
 return out;
}

// ---- Xiang numbers: a line is three counts of 2 (broken) or 3 (whole) (Rutt p.163) ----
// 6 mature yin (changeable), 7 young yang (stable), 8 young yin (stable), 9 mature yang (changeable).
export const XIANG=Object.freeze({6:{yang:0,changeable:true,name:'mature yin'},7:{yang:1,changeable:false,name:'young yang'},8:{yang:0,changeable:false,name:'young yin'},9:{yang:1,changeable:true,name:'mature yang'}});
export const xiangFromCounts=([a,b,c])=>{for(const v of [a,b,c])check(v===2||v===3,'each count is 2 or 3');return a+b+c;};
// Odds per line, as counts out of 16 (Rutt pp.167-168): yarrow 12/28/20/4 of 64; three coins 1/3/3/1 of 8.
export const ODDS=Object.freeze({yarrow:{6:1,7:5,8:7,9:3},coins:{6:2,7:6,8:6,9:2}});
// Turn a number u in [0,1) into a line by the chosen method's odds (the caller supplies u).
export function drawLine(u,method='yarrow'){
 check(u>=0&&u<1,'u must be in [0,1)');const odds=ODDS[method];check(odds,'method is yarrow or coins');
 let acc=0;for(const v of [6,7,8,9]){acc+=odds[v]/16;if(u<acc)return v;}return 9;
}
export function cast(xiangLines){
 check(Array.isArray(xiangLines)&&xiangLines.length===6&&xiangLines.every(v=>XIANG[v]),'six xiang numbers (6,7,8,9), bottom first');
 const base=figureFromLines(xiangLines.map(v=>XIANG[v].yang));
 const changing=xiangLines.map((v,i)=>XIANG[v].changeable?i+1:null).filter(Boolean);
 const result=changing.reduce((f,l)=>f^(1<<(l-1)),base);
 return {lines:[...xiangLines],base:gateOf(base),changing,result:gateOf(result),total:xiangLines.reduce((s,v)=>s+v,0)};
}

// ---- Nanjing rules: which text speaks (Rutt pp.170-171) ----
// 55 minus the six xiang numbers leaves 1..19, which counts up the lines and back down.
export function nanjingLine(total){
 const r=55-total;check(Number.isInteger(r)&&r>=1&&r<=19,'total must be 36..54');
 if(r<=6)return r;if(r<=12)return 13-r;if(r<=18)return r-12;return 6;
}
export function oracle(xiangLines){
 const c=cast(xiangLines),line=nanjingLine(c.total),n=c.changing.length;
 if(n===0)return {...c,line,speaks:'hexagram',hexagrams:[c.base],rule:1};
 if(n===6)return {...c,line,speaks:(c.base===1||c.base===2)?'seventh line (all lines)':'hexagram',hexagrams:(c.base===1||c.base===2)?[c.base]:[c.result],rule:2};
 if(c.changing.includes(line))return {...c,line,speaks:'line',hexagrams:[c.base],rule:3};
 if(n<3)return {...c,line,speaks:'hexagram',hexagrams:[c.base],rule:'4a'};
 if(n===3)return {...c,line,speaks:'both hexagrams',hexagrams:[c.base,c.result],rule:'4b'};
 return {...c,line,speaks:'hexagram',hexagrams:[c.result],rule:'4c'};
}

// ---- What a line statement is made of (Rutt pp.131-134) ----
export const LINE_PARTS=Object.freeze(['oracle','indication','prognostic','observation']);
export const PROGNOSTICS=Object.freeze({ji:'auspicious',li:'dangerous',jiu:'misfortune',xiong:'disastrous'});
// Line positions in the Ten Wings' analysis; Rutt: a tendency, not a consistent feature.
export const POSITIONS=Object.freeze({1:'beginning, hard to understand',2:'interior, encouraging',3:'difficulty, inauspicious',4:'officer, warning',5:'ruler, auspicious',6:'beyond the limit, easy to understand',status:'Ten Wings tendency, not consistent in the oracles'});

// ---- Olsvanger's grid (Rutt pp.108-112) ----
// Binary values in the received order on an 8x8 grid, read from the top right. Olsvanger
// writes the bottom line as the highest digit (the reverse of the Fuxi table).
export const olsvangerValue=gate=>figureFromLines(linesOf(figureOf(gate)).reverse());
export function olsvangerGrid(){
 return Array.from({length:8},(_,row)=>Array.from({length:8},(_,col)=>olsvangerValue(row*8+(8-col))));
}
